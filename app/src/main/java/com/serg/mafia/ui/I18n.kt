package com.serg.mafia.ui

import androidx.compose.runtime.Composable
import androidx.compose.runtime.ReadOnlyComposable
import androidx.compose.runtime.staticCompositionLocalOf

/**
 * Язык интерфейса. По умолчанию украинский — за столом играют на нём,
 * русский и английский переключаются в настройках партии.
 */
enum class Lang(val code: String, val label: String) {
    UK("uk", "Українська"),
    RU("ru", "Русский"),
    EN("en", "English"),
    ;

    companion object {
        fun of(code: String?): Lang = entries.firstOrNull { it.code == code } ?: UK
    }
}

val LocalLang = staticCompositionLocalOf { Lang.UK }

/** Строка по ключу на текущем языке. Подстановки — обычный String.format («%s», «%d»). */
@Composable
@ReadOnlyComposable
fun t(key: String, vararg args: Any?): String = tr(LocalLang.current, key, *args)

/** Сырой шаблон без подстановки — нужен там, где «%d» подставят позже (имена игроков). */
fun rawString(lang: Lang, key: String): String =
    STRINGS[lang]?.get(key) ?: STRINGS[Lang.UK]?.get(key) ?: key

/** То же вне композиции (журнал, тексты для логов). */
fun tr(lang: Lang, key: String, vararg args: Any?): String {
    val template = STRINGS[lang]?.get(key) ?: STRINGS[Lang.UK]?.get(key) ?: key
    return if (args.isEmpty()) template else String.format(template, *args)
}

